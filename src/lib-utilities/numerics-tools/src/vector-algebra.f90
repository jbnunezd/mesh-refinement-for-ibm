MODULE MOD_VectorAlgebra
!----------------------------------------------------------------------------------------------------------------------!
USE MOD_GLOBAL_vars
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
PRIVATE
!----------------------------------------------------------------------------------------------------------------------!
INTERFACE CROSSPRODUCT
  MODULE PROCEDURE CROSSPRODUCT
END INTERFACE

INTERFACE DOTPRODUCT
  MODULE PROCEDURE DOTPRODUCT
END INTERFACE

INTERFACE COMPAREPOINTS
  MODULE PROCEDURE COMPAREPOINTS
END INTERFACE

INTERFACE NORMALIZE
  MODULE PROCEDURE NORMALIZE
END INTERFACE
!----------------------------------------------------------------------------------------------------------------------!
PUBLIC :: CROSSPRODUCT
PUBLIC :: DOTPRODUCT
PUBLIC :: NORMALIZE
PUBLIC :: COMPAREPOINTS
!----------------------------------------------------------------------------------------------------------------------!
CHARACTER(LEN=256) :: ModuleName = "NumericsTools::VectorAlgebra"
!----------------------------------------------------------------------------------------------------------------------!
!
!
!
!======================================================================================================================!
CONTAINS
!======================================================================================================================!
!
!
!
!======================================================================================================================!
FUNCTION CROSSPRODUCT(v1,v2) RESULT(v3)
!----------------------------------------------------------------------------------------------------------------------!
! Cross product
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
REAL,INTENT(IN) :: v1(1:3)
REAL,INTENT(IN) :: v2(1:3)
REAL            :: v3(1:3)
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!

v3(1) = v1(2)*v2(3)-v1(3)*v2(2)
v3(2) = v1(3)*v2(1)-v1(1)*v2(3)
v3(3) = v1(1)*v2(2)-v1(2)*v2(1)

!----------------------------------------------------------------------------------------------------------------------!
END FUNCTION CROSSPRODUCT
!======================================================================================================================!
!
!
!
!======================================================================================================================!
FUNCTION DOTPRODUCT(v1,v2) RESULT(v)
!----------------------------------------------------------------------------------------------------------------------!
! Dot product
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
REAL,INTENT(IN) :: v1(:)
REAL,INTENT(IN) :: v2(:)
REAL            :: v
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!
INTEGER :: ii
!----------------------------------------------------------------------------------------------------------------------!
CHARACTER(LEN=256) :: ErrorMessage
CHARACTER(LEN=256) :: FunctionName = "DOTPRODUCT"
!----------------------------------------------------------------------------------------------------------------------!

IF (SIZE(v1) .NE. SIZE(v2)) THEN
  ErrorMessage = "DOTPRODUCT: Vectors have different size"
  CALL PrintError(__STAMP__,ErrorMessage,ModuleName,FunctionName)
END IF

v = 0.0
DO ii=1,SIZE(v1)
  v = v + v1(ii)*v2(ii)
END DO

!----------------------------------------------------------------------------------------------------------------------!
END FUNCTION DOTPRODUCT
!======================================================================================================================!
!
!
!
!======================================================================================================================!
FUNCTION NORMALIZE(v_in) RESULT(v_out)
!----------------------------------------------------------------------------------------------------------------------!
! Dot product
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
REAL,INTENT(IN) :: v_in(:)
REAL            :: v_out(1:SIZE(v_in))
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!
REAL :: vectornorm
!----------------------------------------------------------------------------------------------------------------------!
CHARACTER(LEN=256) :: ErrorMessage
CHARACTER(LEN=256) :: FunctionName = "NORMALIZE"
!----------------------------------------------------------------------------------------------------------------------!

IF (SIZE(v_in) .NE. SIZE(v_out)) THEN
  ErrorMessage = "NORMALIZE: Vectors have different size"
  CALL PrintError(__STAMP__,ErrorMessage,ModuleName,FunctionName)
END IF

vectornorm = DOTPRODUCT(v_in,v_in)
vectornorm = SQRT(vectornorm)

IF (vectornorm .GT. 0.0) THEN
  v_out = v_in/vectornorm
ELSE
  v_out = v_in
END IF

!----------------------------------------------------------------------------------------------------------------------!
END FUNCTION NORMALIZE
!======================================================================================================================!
!
!
!
!======================================================================================================================!
FUNCTION COMPAREPOINTS(Point1,Point2) RESULT(Flag)
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
REAL,INTENT(IN) :: Point1(:)
REAL,INTENT(IN) :: Point2(:)
LOGICAL         :: Flag
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!
REAL            :: ds
!----------------------------------------------------------------------------------------------------------------------!

ds = SQRT(DOT_PRODUCT(Point1-Point2,Point1-Point2))
Flag = .FALSE.
IF (ds .LT. PP_ACCURACY) THEN
  Flag = .TRUE.
END IF

!----------------------------------------------------------------------------------------------------------------------!
END FUNCTION COMPAREPOINTS
!======================================================================================================================!
!
!
!
!----------------------------------------------------------------------------------------------------------------------!
END MODULE MOD_VectorAlgebra
