! ! ! REAL,INTENT(IN)    :: xc(1:8,1:3)
! ! ! REAL,INTENT(OUT)   :: x(1:3)
! ! ! !----------------------------------------------------------------------------------------------------------------------!
! ! ! ! LOCAL VARIABLES
! ! ! !----------------------------------------------------------------------------------------------------------------------!
! ! ! REAL :: r0
! ! ! REAL :: r1
! ! ! REAL :: bump
! ! ! REAL :: dx
! ! ! REAL :: dy
! ! ! !----------------------------------------------------------------------------------------------------------------------!
! ! ! 
! ! ! r0   = 0.5
! ! ! r1   = 5.0
! ! ! dx   = 20.0
! ! ! dy   = 5.0
! ! ! bump = r0*(1.0-(MIN(dx/r1,1.0))**2)**6
! ! ! 
! ! ! ! TODO: Formula for 3D
! ! ! SELECT CASE(WhichFace)
! ! !   CASE(1)
! ! !     x(1) = dx*s
! ! !     x(2) = r0*(1.0-(MIN(ABS(dx*s)/r1,1.0))**2)**6
! ! !   CASE(2)
! ! !     x(1) = dx
! ! !     x(2) = bump*(1.0-s)*0.5 + dy*(1.0+s)
! ! !   CASE(3)
! ! !     x(1) = dx*s
! ! !     x(2) = 2.0*dy
! ! !   CASE(4)
! ! !     x(1) = -dx
! ! !     x(2) = bump*(1.0-s)*0.5 + dy*(1.0+s)
! ! ! END SELECT
! ! ! 
! ! ! !----------------------------------------------------------------------------------------------------------------------!
! ! ! END SUBROUTINE Mapping3D_SineBump
