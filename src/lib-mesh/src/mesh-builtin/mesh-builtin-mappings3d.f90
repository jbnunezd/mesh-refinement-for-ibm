SUBROUTINE Mapping3D_FullCylinder(WhichFace,s,xc,x)
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
INTEGER,INTENT(IN) :: WhichFace
REAL,INTENT(IN)    :: s(1:2)
REAL,INTENT(IN)    :: xc(1:8,1:3)
REAL,INTENT(OUT)   :: x(1:3)
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!
REAL :: PI
REAL :: r0
REAL :: r1
REAL :: L
!----------------------------------------------------------------------------------------------------------------------!

r0 = 0.45
r1 = 20.0
L  = 1.0
PI = ACOS(-1.0)

SELECT CASE(WhichFace)
  CASE(1)
    x(1) =+r0*COS(PI*(1.0+s(1)))
    x(2) = L*s(2)
    x(3) =-r0*SIN(PI*(1.0+s(1)))
  CASE(2)
    x(1) = 0.5*((r0 +  (r1-r0)*(1.0+s(2))*0.5)*(1.0-s(1)) + &
                (r0 +  (r1-r0)*(1.0+s(2))    )*(1.0+s(1)) + &
                (       r0*COS(PI*(1.0+s(1))))*(1.0-s(2)) + &
                (       r1*COS(PI*(1.0+s(1))))*(1.0+s(2))) &
          -0.25*(r0*(1.0-s(2))*(1.0-s(1)) + &
                 r1*(1.0+s(2))*(1.0-s(1)) + &
                 r0*(1.0-s(2))*(1.0+s(1)) + &
                 r1*(1.0+s(2))*(1.0+s(1)))
    x(2) = -L
    x(3) = 0.5*((-r0*SIN(PI*(1.0+s(1))))*(1.0-s(2)) + &
                (-r1*SIN(PI*(1.0+s(1))))*(1.0+s(2)) )
  CASE(3)
    x(1) = (r0+(r1-r0)*(1.0+s(2))*0.5)
    x(2) = L*s(1)
    x(3) = 0.0
  CASE(4)
    x(1) = 0.5*((r0 +  (r1-r0)*(1.0+s(2))*0.5)*(1.0-s(1)) + &
                (r0 +  (r1-r0)*(1.0+s(2))    )*(1.0+s(1)) + &
                (       r0*COS(PI*(1.0+s(1))))*(1.0-s(2)) + &
                (       r1*COS(PI*(1.0+s(1))))*(1.0+s(2))) &
          -0.25*(r0*(1.0-s(2))*(1.0-s(1)) + &
                 r1*(1.0+s(2))*(1.0-s(1)) + &
                 r0*(1.0-s(2))*(1.0+s(1)) + &
                 r1*(1.0+s(2))*(1.0+s(1)))
    x(2) = L
    x(3) = 0.5*((-r0*SIN(PI*(1.0+s(1))))*(1.0-s(2)) + &
                (-r1*SIN(PI*(1.0+s(1))))*(1.0+s(2)) )
  CASE(5)
    x(1) = (r0+(r1-r0)*(1.0+s(2))*0.5)
    x(2) = L*s(1)
    x(3) = 0.0
  CASE(6)
    x(1) =+r1*COS(PI*(1.0+s(1)))
    x(2) = L*s(2)
    x(3) =-r1*SIN(PI*(1.0+s(1)))
END SELECT

!----------------------------------------------------------------------------------------------------------------------!
END SUBROUTINE Mapping3D_FullCylinder
