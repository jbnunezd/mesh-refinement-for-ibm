SUBROUTINE MeshStretching2D_Uniform(nElems,dx,dy)
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
INTEGER,INTENT(IN) :: nElems(1:2)
REAL,INTENT(OUT)   :: dx(1:nElems(1))
REAL,INTENT(OUT)   :: dy(1:nElems(2))
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!

dx(1:nElems(1)) = 1.0
dy(1:nElems(2)) = 1.0

dx = dx*(2.0/SUM(dx(1:nElems(1))))
dy = dy*(2.0/SUM(dy(1:nElems(2))))

!----------------------------------------------------------------------------------------------------------------------!
END SUBROUTINE MeshStretching2D_Uniform
!======================================================================================================================!
!
!
!
!======================================================================================================================!
SUBROUTINE MeshStretching2D_GeometricProgression(nElems,dx,dy)
!----------------------------------------------------------------------------------------------------------------------!
USE MOD_MeshBuiltIn_vars,ONLY: ParametersMeshBuiltIn2D
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
INTEGER,INTENT(IN) :: nElems(1:2)
REAL,INTENT(OUT)   :: dx(1:nElems(1))
REAL,INTENT(OUT)   :: dy(1:nElems(2))
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!
INTEGER :: ii
REAL    :: alpha(1:2)
!----------------------------------------------------------------------------------------------------------------------!

alpha(1:2) = ParametersMeshBuiltIn2D%MeshStretchingFactor2D(1:2)

dx(1) = 1.0
dy(1) = 1.0

DO ii=2,nElems(1)
  dx(ii) = dx(ii-1)*alpha(1)
END DO
DO ii=2,nElems(2)
  dy(ii) = dy(ii-1)*alpha(2)
END DO

dx = dx*(2.0/SUM(dx(1:nElems(1))))
dy = dy*(2.0/SUM(dy(1:nElems(2))))

!----------------------------------------------------------------------------------------------------------------------!
END SUBROUTINE MeshStretching2D_GeometricProgression
!======================================================================================================================!
!
!
!
!======================================================================================================================!
SUBROUTINE MeshStretching2D_TwoSidesBoundariesHyperbolic(nElems,dx,dy)
!----------------------------------------------------------------------------------------------------------------------!
USE MOD_MeshBuiltIn_vars,ONLY: ParametersMeshBuiltIn2D
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
INTEGER,INTENT(IN) :: nElems(1:2)
REAL,INTENT(OUT)   :: dx(1:nElems(1))
REAL,INTENT(OUT)   :: dy(1:nElems(2))
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!
INTEGER :: ii
REAL    :: ds
REAL    :: s
REAL    :: alpha(1:2)
!----------------------------------------------------------------------------------------------------------------------!

alpha(1:2) = ParametersMeshBuiltIn2D%MeshStretchingFactor2D(1:2)

IF (nElems(1) .EQ. 1) THEN
  ds = 2.0
  dx = ds
ELSE
  ds = 2.0/REAL(nElems(1)-1.0)
  s = -1.0
  DO ii=1,nElems(1)
    dx(ii) = ds*ABS(1.0-TANH(alpha(1)*ABS(s)))
    s = s+ds
  END DO
END IF

IF (nElems(2) .EQ. 1) THEN
  ds = 2.0
  dy = ds
ELSE
  ds = 2.0/REAL(nElems(2)-1.0)
  s = -1.0
  DO ii=1,nElems(2)
    dy(ii) = ds*ABS(1.0-TANH(alpha(2)*ABS(s)))
    s = s+ds
  END DO
END IF

dx = dx*(2.0/SUM(dx(1:nElems(1))))
dy = dy*(2.0/SUM(dy(1:nElems(2))))

!----------------------------------------------------------------------------------------------------------------------!
END SUBROUTINE MeshStretching2D_TwoSidesBoundariesHyperbolic
!======================================================================================================================!
!
!
!
!======================================================================================================================!
SUBROUTINE MeshStretching2D_TwoSidesBoundariesPotential(nElems,dx,dy)
!----------------------------------------------------------------------------------------------------------------------!
USE MOD_MeshBuiltIn_vars,ONLY: ParametersMeshBuiltIn2D
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
INTEGER,INTENT(IN) :: nElems(1:2)
REAL,INTENT(OUT)   :: dx(1:nElems(1))
REAL,INTENT(OUT)   :: dy(1:nElems(2))
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!
INTEGER :: ii
REAL    :: ds
REAL    :: s
REAL    :: alpha(1:2)
!----------------------------------------------------------------------------------------------------------------------!

alpha(1:2) = ParametersMeshBuiltIn2D%MeshStretchingFactor2D(1:2)

IF (nElems(1) .EQ. 1) THEN
  ds = 2.0
  dx = ds
ELSE
  ds = 2.0/REAL(nElems(1)-1.0)
  s = -1.0
  DO ii=1,nElems(1)
    dx(ii) = ds*(1.0/(1.0+(alpha(1)*ABS(s))**6))
    s = s+ds
  END DO
END IF

IF (nElems(2) .EQ. 1) THEN
  ds = 2.0
  dy = ds
ELSE
  ds = 2.0/REAL(nElems(2)-1.0)
  s = -1.0
  DO ii=1,nElems(2)
    dy(ii) = ds*(1.0/(1.0+(alpha(2)*ABS(s))**6))
    s = s+ds
  END DO
END IF

dx = dx*(2.0/SUM(dx(1:nElems(1))))
dy = dy*(2.0/SUM(dy(1:nElems(2))))

!----------------------------------------------------------------------------------------------------------------------!
END SUBROUTINE MeshStretching2D_TwoSidesBoundariesPotential
