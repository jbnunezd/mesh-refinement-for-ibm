SUBROUTINE Mapping2D_StraightQuad(WhichCurve,s,xc,x)
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
INTEGER,INTENT(IN) :: WhichCurve
REAL,INTENT(IN)    :: s
REAL,INTENT(IN)    :: xc(1:4,1:2)
REAL,INTENT(OUT)   :: x(1:2)
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!

SELECT CASE(WhichCurve)
  CASE(1)
    x(1) = 0.5*(xc(1,1)*(1.0-s) + xc(2,1)*(1.0+s))
    x(2) = 0.5*(xc(1,2)*(1.0-s) + xc(2,2)*(1.0+s))
  CASE(2)
    x(1) = 0.5*(xc(2,1)*(1.0-s) + xc(3,1)*(1.0+s))
    x(2) = 0.5*(xc(2,2)*(1.0-s) + xc(3,2)*(1.0+s))
  CASE(3)
    x(1) = 0.5*(xc(4,1)*(1.0-s) + xc(3,1)*(1.0+s))
    x(2) = 0.5*(xc(4,2)*(1.0-s) + xc(3,2)*(1.0+s))
  CASE(4)
    x(1) = 0.5*(xc(1,1)*(1.0-s) + xc(4,1)*(1.0+s))
    x(2) = 0.5*(xc(1,2)*(1.0-s) + xc(4,2)*(1.0+s))
END SELECT

!----------------------------------------------------------------------------------------------------------------------!
END SUBROUTINE Mapping2D_StraightQuad
