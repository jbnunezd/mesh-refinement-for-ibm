SUBROUTINE Mapping2D_FullDisk(WhichCurve,s,xc,x)
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
INTEGER,INTENT(IN) :: WhichCurve
REAL,INTENT(IN)    :: s
REAL,INTENT(IN)    :: xc(1:4,1:2)
REAL,INTENT(OUT)   :: x(1:2)
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!
REAL :: PI
REAL :: r0
REAL :: r1
!----------------------------------------------------------------------------------------------------------------------!

r0 = 0.5
r1 = 10.0
PI = ACOS(-1.0)

SELECT CASE(WhichCurve)
  CASE(1)
    x(1) = r0*COS(PI*(1.0+s))
    x(2) = r0*SIN(PI*(1.0+s))
  CASE(2)
    x(1) = (r0+(r1-r0)*(1.0+s)*0.5)
    x(2) = 0.0
  CASE(3)
    x(1) = r1*COS(PI*(1.0+s))
    x(2) = r1*SIN(PI*(1.0+s))
  CASE(4)
    x(1) = (r0+(r1-r0)*(1.0+s)*0.5)
    x(2) = 0.0
END SELECT

!----------------------------------------------------------------------------------------------------------------------!
END SUBROUTINE Mapping2D_FullDisk
