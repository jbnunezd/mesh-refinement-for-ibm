SUBROUTINE Mapping2D_Nozzle(WhichCurve,s,xc,x)
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
INTEGER,INTENT(IN) :: WhichCurve
REAL,INTENT(IN)    :: s
REAL,INTENT(IN)    :: xc(1:4,1:2)
REAL,INTENT(OUT)   :: x(1:2)
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!

SELECT CASE(WhichCurve)
  CASE(1)
    x(1) = +1.5*s
    x(2) = -(0.3+0.35*(TANH(+2.0*s)+1.0))
  CASE(2)
    x(1) = +1.5 
    x(2) = (0.3+0.35*(TANH(+2.0)+1.0))*s
  CASE(3)
    x(1) = +1.5*s
    x(2) = +(0.3+0.35*(TANH(+2.0*s)+1.0))
  CASE(4)
    x(1) = -1.5
    x(2) = (0.3+0.35*(TANH(-2.0)+1.0))*s
END SELECT

!----------------------------------------------------------------------------------------------------------------------!
END SUBROUTINE Mapping2D_Nozzle
