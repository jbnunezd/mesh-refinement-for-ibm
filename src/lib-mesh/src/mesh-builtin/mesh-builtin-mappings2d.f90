SUBROUTINE Mapping2D_CurvedChannel(WhichCurve,s,xc,x)
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
INTEGER,INTENT(IN) :: WhichCurve
REAL,INTENT(IN)    :: s
REAL,INTENT(IN)    :: xc(1:4,1:2)
REAL,INTENT(OUT)   :: x(1:2)
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!
REAL :: PI
!----------------------------------------------------------------------------------------------------------------------!

PI = ACOS(-1.0)

SELECT CASE(WhichCurve)
  CASE(1)
    x(1) = 8.0+7.75*COS(PI*(1.0+0.25*(1.0+s)))
    x(2) = 1.0/(8.0+7.75*COS(PI*(1.0+0.25*(1.0+s))))
  CASE(2)
    x(1) = 8.0
    x(2) = 0.125+1.125*(1.0+s)*0.5
  CASE(3)
    x(1) = 8.0+5.50*COS(PI*(1.0+0.25*(1.0+s)))
    x(2) = 1.0/(1.0+0.75*COS(PI*(1.0+0.25*(1.0+s))))
  CASE(4)
    x(1) = 0.25+2.25*(1.0+s)*0.5
    x(2) = 4.0
END SELECT

!----------------------------------------------------------------------------------------------------------------------!
END SUBROUTINE Mapping2D_CurvedChannel
