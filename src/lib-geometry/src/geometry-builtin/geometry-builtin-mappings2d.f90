MODULE MOD_GeometryBuiltInMappings2D
!----------------------------------------------------------------------------------------------------------------------!
USE MOD_GLOBAL_vars
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
PRIVATE
!----------------------------------------------------------------------------------------------------------------------!
INTERFACE GeometryMapping2D_Circle
  MODULE PROCEDURE GeometryMapping2D_Circle
END INTERFACE

INTERFACE GeometryMapping2D_Ellipse
  MODULE PROCEDURE GeometryMapping2D_Ellipse
END INTERFACE
!----------------------------------------------------------------------------------------------------------------------!
PUBLIC :: GeometryMapping2D_Circle
PUBLIC :: GeometryMapping2D_Ellipse
!----------------------------------------------------------------------------------------------------------------------!
!
!
!
!======================================================================================================================!
CONTAINS
!======================================================================================================================!
!
!
!
!======================================================================================================================!
SUBROUTINE GeometryMapping2D_Circle(s,xc,x)
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
REAL,INTENT(IN)  :: s
REAL,INTENT(IN)  :: xc(1:2)
REAL,INTENT(OUT) :: x(1:2)
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!
REAL :: R
!----------------------------------------------------------------------------------------------------------------------!

R = 1.0

x(1) = xc(1) + R*COS(s)
x(2) = xc(2) + R*SIN(s)

!----------------------------------------------------------------------------------------------------------------------!
END SUBROUTINE GeometryMapping2D_Circle
!======================================================================================================================!
!
!
!
!======================================================================================================================!
SUBROUTINE GeometryMapping2D_Ellipse(s,xc,x)
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
REAL,INTENT(IN)  :: s
REAL,INTENT(IN)  :: xc(1:2)
REAL,INTENT(OUT) :: x(1:2)
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!
REAL :: a
REAL :: b
!----------------------------------------------------------------------------------------------------------------------!

a = 0.2
b = 0.6

x(1) = xc(1) + a*COS(s)
x(2) = xc(2) + b*SIN(s)

!----------------------------------------------------------------------------------------------------------------------!
END SUBROUTINE GeometryMapping2D_Ellipse
!======================================================================================================================!
!
!
!
!----------------------------------------------------------------------------------------------------------------------!
END MODULE MOD_GeometryBuiltInMappings2D
