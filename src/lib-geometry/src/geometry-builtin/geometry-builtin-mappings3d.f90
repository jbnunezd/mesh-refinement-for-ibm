MODULE MOD_GeometryBuiltInMappings3D
!----------------------------------------------------------------------------------------------------------------------!
USE MOD_GLOBAL_vars
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
PRIVATE
!----------------------------------------------------------------------------------------------------------------------!
INTERFACE GeometryMapping3D_Point
  MODULE PROCEDURE GeometryMapping3D_Point
END INTERFACE

INTERFACE GeometryMapping3D_Sphere
  MODULE PROCEDURE GeometryMapping3D_Sphere
END INTERFACE
!----------------------------------------------------------------------------------------------------------------------!
PUBLIC :: GeometryMapping3D_Point
PUBLIC :: GeometryMapping3D_Sphere
!----------------------------------------------------------------------------------------------------------------------!
!
!
!
!======================================================================================================================!
CONTAINS
!======================================================================================================================!
!
!
!
!======================================================================================================================!
SUBROUTINE GeometryMapping3D_Point(s,xc,x)
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
REAL,INTENT(IN)  :: s(1:2)
REAL,INTENT(IN)  :: xc(1:3)
REAL,INTENT(OUT) :: x(1:3)
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!

x(1) = xc(1)
x(2) = xc(2)
x(3) = xc(3)

!----------------------------------------------------------------------------------------------------------------------!
END SUBROUTINE GeometryMapping3D_Point
!======================================================================================================================!
!
!
!
!======================================================================================================================!
SUBROUTINE GeometryMapping3D_Sphere(s,xc,x)
!----------------------------------------------------------------------------------------------------------------------!
IMPLICIT NONE
!----------------------------------------------------------------------------------------------------------------------!
! FORMAL ARGUMENTS
!----------------------------------------------------------------------------------------------------------------------!
REAL,INTENT(IN)  :: s(1:2)
REAL,INTENT(IN)  :: xc(1:3)
REAL,INTENT(OUT) :: x(1:3)
!----------------------------------------------------------------------------------------------------------------------!
! LOCAL VARIABLES
!----------------------------------------------------------------------------------------------------------------------!
REAL :: R
!----------------------------------------------------------------------------------------------------------------------!

R = 0.5

x(1) = xc(1) + R*COS(s(1))*SIN(s(2))
x(2) = xc(2) + R*SIN(s(1))*SIN(s(2))
x(3) = xc(3) + R*COS(s(2))

!----------------------------------------------------------------------------------------------------------------------!
END SUBROUTINE GeometryMapping3D_Sphere
!======================================================================================================================!
!
!
!
!----------------------------------------------------------------------------------------------------------------------!
END MODULE MOD_GeometryBuiltInMappings3D
